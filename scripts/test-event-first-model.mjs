import assert from 'node:assert/strict'
import { readFileSync, existsSync } from 'node:fs'

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8')
const app = read('../src/App.jsx')
const events = read('../src/pages/Events.jsx')
const detail = read('../src/pages/EventDetail.jsx')
const sidebar = read('../src/components/Sidebar.jsx')
const navbar = read('../src/components/Navbar.jsx')
const profile = read('../src/pages/Profile.jsx')
const migration = read('../supabase/migrations/20261109000000_direct_event_ownership_no_workspaces.sql')
const pricing = read('../src/pages/Pricing.jsx')

assert(!app.includes("'/workspace/setup'") && !app.includes("'/workspace/members'"), 'workspace routes must not be exposed')
assert(!sidebar.includes("'/workspace/setup'") && !sidebar.includes("'/workspace/members'"), 'workspace navigation must be removed')
assert(!navbar.includes("'/workspace/setup'") && !navbar.includes("'/workspace/members'"), 'workspace account menu must be removed')
assert(events.includes("accountType === 'organiser'"), 'only organiser accounts may create events')
assert(events.includes('organization_id: null'), 'new events must not depend on an organization workspace')
assert(detail.includes("event?.organizer_id === user.id"), 'event management must be based on direct ownership')
assert(detail.includes('exportParticipants') && detail.includes('removeParticipant'), 'organiser needs participant management actions')
assert(migration.includes('organizer_id=p_user') && migration.includes('public.can_manage_collivra_event'), 'database permissions must use direct event ownership')
assert(migration.includes('event creator removes participants'), 'database must permit creator participant management')
assert(!profile.includes('organiser_category') && !profile.includes('create_organization_workspace'), 'organiser profile must not require a category or workspace')
assert(!profile.includes('Account type</label>') && profile.includes('accountType={ownProfile?.account_type'), 'profile setup must preserve the account type selected at signup')
assert(!sidebar.includes("label: 'My Teams'") && !navbar.includes("label: 'My teams'"), 'student navigation must not expose the removed My Teams area')
assert(!pricing.includes('organiser_monthly') && !pricing.includes('organiser_yearly'), 'organiser recurring plans must not be offered in the current pricing UI')
assert(pricing.includes('Custom') && pricing.includes('Request a quote'), 'organiser billing must retain Enterprise custom quotes')
assert(pricing.includes('Successful verified payment unlocks publishing'), 'Event Pass must be described as the verified publish gate')
assert(pricing.includes('Create and save event drafts for free'), 'organiser drafts must remain free')
assert(existsSync(new URL('../src/pages/ForgotPassword.jsx', import.meta.url)), 'forgot password page must remain in project')
assert(existsSync(new URL('../src/pages/ResetPassword.jsx', import.meta.url)), 'reset password page must remain in project')
console.log('ok - event-first account model, direct event ownership, participant controls, unified billing and password reset routes')
